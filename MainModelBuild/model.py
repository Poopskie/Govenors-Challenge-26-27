"""Bayesian VAR forecasting engine for the Governor's Challenge.

The model expects quarterly, already-transformed data.  A practical default
specification is:

    real_brent, us_gdp_growth, ca_gdp_growth, core_inflation,
    headline_inflation, ca_exchange_rate

The engine uses a conjugate Bayesian ridge approximation to a Minnesota prior.
This keeps the first reduced-form version transparent and dependency-light.
When component levels are supplied, Canadian GDP is generated by the attached
GDP component model from the BVAR's simulated driver paths.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Mapping, Sequence

import numpy as np
import pandas as pd


@dataclass(frozen=True)
class BVARConfig:
    """Hyperparameters for the reduced-form Bayesian VAR."""

    lags: int = 8
    prior_tightness: float = 0.01
    policy_prior_tightness: float = 1.0
    policy_shock_prior_tightness: float = 1.0
    prior_decay: float = 1.0
    draws: int = 2_000
    forecast_horizon: int = 12
    random_seed: int = 42
    # Shrinks unstable reduced-form shock draws without changing forecast means.
    # This is calibrated for the short sample and volatile oil-growth series.
    forecast_uncertainty_scale: float = 0.1
    policy_shock_persistence: float = 0.75
    # Structural monetary-transmission effect in percentage points of inflation
    # per percentage-point policy-rate gap, applied to core and headline CPI.
    inflation_policy_sensitivity: float = 0.25
    inflation_policy_lag_weight: float = 0.5
    inflation_persistence: float = 0.8
    # Structural GDP response in annualized percentage points per one-point
    # policy-rate gap; higher rates should reduce GDP growth.
    gdp_policy_sensitivity: float = 0.5
    random_walk_variables: tuple[str, ...] = ("ca_exchange_rate",)
    policy_variable: str = "overnight_rate"


class BayesianVAR:
    """Estimate a quarterly Bayesian VARX with a monetary policy shock.

    ``fit`` takes a DataFrame whose columns are transformed quarterly series.
    For example, GDP and prices should normally be quarter-over-quarter
    annualized growth rates, while interest rates can remain in percentage
    points.  Missing values are rejected rather than silently imputed.
    Forecasts propagate policy-rate changes as persistent monetary shocks.
    """

    def __init__(
        self,
        config: BVARConfig | None = None,
        variables: Sequence[str] | None = None,
    ) -> None:
        self.config = config or BVARConfig()
        if (
            self.config.lags < 1
            or self.config.draws < 1
            or self.config.policy_prior_tightness <= 0
            or self.config.policy_shock_prior_tightness <= 0
            or self.config.forecast_uncertainty_scale <= 0
            or self.config.inflation_policy_sensitivity < 0
            or self.config.inflation_policy_lag_weight < 0
            or not 0 <= self.config.inflation_persistence <= 1
            or self.config.gdp_policy_sensitivity < 0
            or not 0 <= self.config.policy_shock_persistence <= 1
        ):
            raise ValueError(
                "lags, draws, policy prior tightness values, and forecast uncertainty "
                "scale must be positive"
            )
        self.variables = list(variables) if variables is not None else [
            "real_brent",
            "us_gdp_growth",
            "ca_gdp_growth",
            "core_inflation",
            "headline_inflation",
            "ca_exchange_rate",
        ]
        if len(self.variables) == 0:
            raise ValueError("at least one variable is required")
        self._gdp_model = None
        self._fitted = False

    def fit(
        self,
        data: pd.DataFrame,
        component_levels: pd.DataFrame | None = None,
    ) -> "BayesianVAR":
        """Fit the BVAR and return ``self``.

        The input index must be quarterly or otherwise ordered chronologically.
        At least ``lags + 5`` complete observations are required.
        """
        if component_levels is not None and "ca_gdp_growth" not in self.variables:
            raise ValueError("integrated GDP forecasting requires ca_gdp_growth in variables")
        fit_variables = [
            name for name in self.variables
            if component_levels is None or name != "ca_gdp_growth"
        ]
        required = [*fit_variables, self.config.policy_variable]
        missing = [name for name in required if name not in data.columns]
        if missing:
            raise ValueError(f"missing model columns: {', '.join(missing)}")
        frame = data.loc[:, required].copy()
        if frame.isna().any().any():
            bad = frame.columns[frame.isna().any()].tolist()
            raise ValueError(f"missing values in model columns: {', '.join(bad)}")
        if len(frame) <= self.config.lags + 5:
            raise ValueError("not enough observations for the requested lag length")

        if component_levels is not None:
            from gdpmodel import GDPComponentsModel

            component_levels, aligned_data = component_levels.align(
                data, join="inner", axis=0
            )
            driver_columns = [*fit_variables, self.config.policy_variable]
            self._gdp_model = GDPComponentsModel().fit(
                component_levels,
                drivers=aligned_data.loc[:, driver_columns],
            )
            data = aligned_data
            frame = data.loc[:, required].copy()
        else:
            self._gdp_model = None
        self._fit_variables = fit_variables
        values = frame.loc[:, fit_variables].to_numpy(dtype=float)
        policy = frame[self.config.policy_variable].to_numpy(dtype=float)
        policy_shock = np.diff(policy, prepend=policy[0])
        if not np.isfinite(values).all() or not np.isfinite(policy).all():
            raise ValueError("model data must contain only finite numeric values")

        y = values[self.config.lags :]
        x = np.column_stack(
            [
                np.ones(len(y)),
                *[
                    values[self.config.lags - lag : -lag]
                    for lag in range(1, self.config.lags + 1)
                ],
                policy[self.config.lags :] - policy.mean(),
                policy_shock[self.config.lags :],
            ]
        )
        n_variables = len(fit_variables)
        scale = np.std(y, axis=0, ddof=1)
        scale[scale <= 1e-12] = 1.0

        prior_precision = np.zeros((x.shape[1], x.shape[1]))
        prior_mean = np.zeros((x.shape[1], n_variables))
        prior_precision[0, 0] = 1e-6
        for lag in range(1, self.config.lags + 1):
            for variable in range(n_variables):
                position = 1 + (lag - 1) * n_variables + variable
                prior_variance = (
                    self.config.prior_tightness**2
                    / lag ** (2 * self.config.prior_decay)
                )
                prior_precision[position, position] = 1.0 / max(
                    prior_variance, 1e-12
                )
                if lag == 1 and fit_variables[variable] in self.config.random_walk_variables:
                    prior_mean[position, variable] = 1.0
                if lag == 1 and fit_variables[variable] in {
                    "core_inflation",
                    "headline_inflation",
                }:
                    prior_mean[position, variable] = self.config.inflation_persistence
        policy_position = x.shape[1] - 2
        policy_shock_position = x.shape[1] - 1
        policy_scale = max(float(np.std(policy, ddof=1)), 1e-12)
        policy_shock_scale = max(float(np.std(policy_shock, ddof=1)), 1e-12)
        for equation in range(n_variables):
            prior_precision[policy_position, policy_position] = (
                1.0
                / max(
                    self.config.policy_prior_tightness**2
                    * scale[equation] ** 2
                    / policy_scale**2,
                    1e-12,
                )
            )
            prior_precision[policy_shock_position, policy_shock_position] = (
                1.0
                / max(
                    self.config.policy_shock_prior_tightness**2
                    * scale[equation] ** 2
                    / policy_shock_scale**2,
                    1e-12,
                )
            )

        # Equation-specific scale adjustment: own and cross-variable lags have
        # prior variance proportional to sigma_i^2 / sigma_j^2.
        prior_precision_by_equation = np.zeros(
            (n_variables, x.shape[1], x.shape[1])
        )
        for equation in range(n_variables):
            precision = prior_precision.copy()
            for lag in range(1, self.config.lags + 1):
                for regressor in range(n_variables):
                    position = 1 + (lag - 1) * n_variables + regressor
                    variance = (
                        self.config.prior_tightness**2
                        / lag ** (2 * self.config.prior_decay)
                        * scale[equation] ** 2
                        / scale[regressor] ** 2
                    )
                    precision[position, position] = 1.0 / max(variance, 1e-12)
            precision[policy_position, policy_position] = prior_precision[
                policy_position, policy_position
            ]
            precision[policy_shock_position, policy_shock_position] = prior_precision[
                policy_shock_position, policy_shock_position
            ]
            prior_precision_by_equation[equation] = precision

        coefficients = np.zeros((n_variables, x.shape[1]))
        coefficient_covariances = []
        residuals = np.zeros_like(y)
        for equation in range(n_variables):
            precision = prior_precision_by_equation[equation]
            posterior_precision = x.T @ x + precision
            covariance = np.linalg.inv(
                posterior_precision + np.eye(x.shape[1]) * 1e-10
            )
            mean = covariance @ (
                x.T @ y[:, equation] + precision @ prior_mean[:, equation]
            )
            coefficients[equation] = mean
            coefficient_covariances.append(covariance)
            residuals[:, equation] = y[:, equation] - x @ mean

        residual_covariance = residuals.T @ residuals / max(len(y) - x.shape[1], 1)
        residual_covariance += np.eye(n_variables) * 1e-10
        self._coefficients = coefficients
        self._coefficient_covariances = coefficient_covariances
        self._residual_covariance = residual_covariance
        self._history = values
        self._policy_history = policy
        self._index = frame.index
        self._last_values = values[-self.config.lags :].copy()
        self._fitted = True
        return self

    def forecast(
        self,
        horizon: int | None = None,
        draws: int | None = None,
        future_paths: Mapping[str, Sequence[float]] | None = None,
    ) -> pd.DataFrame:
        """Return posterior forecast means and 80% intervals by quarter.

        The overnight rate is exogenous and must be supplied as a future path.
        Its change is treated as a monetary policy shock and propagated into
        the other BVAR variables using the fitted shock coefficients.
        """
        self._require_fit()
        horizon = self.config.forecast_horizon if horizon is None else horizon
        draws = self.config.draws if draws is None else draws
        if horizon < 1 or draws < 1:
            raise ValueError("horizon and draws must be positive")
        paths = dict(future_paths or {})
        policy_name = self.config.policy_variable
        if policy_name not in paths:
            raise ValueError(f"future_paths must include the exogenous {policy_name!r} path")
        unknown = set(paths) - {policy_name}
        if unknown:
            raise ValueError(f"future path has unknown columns: {sorted(unknown)}")
        for name, path in paths.items():
            path_values = np.asarray(path, dtype=float)
            if len(path_values) != horizon or not np.isfinite(path_values).all():
                raise ValueError(f"future path for {name} must have {horizon} finite values")
            paths[name] = path_values

        rng = np.random.default_rng(self.config.random_seed)
        simulations = np.empty((draws, horizon, len(self.variables)))
        fit_positions = {
            name: position for position, name in enumerate(self._fit_variables)
        }
        policy_path = paths[policy_name]
        for draw in range(draws):
            simulated_coefficients = []
            for equation, covariance in enumerate(self._coefficient_covariances):
                covariance = (covariance + covariance.T) / 2
                covariance += np.eye(covariance.shape[0]) * 1e-10
                simulated_coefficients.append(
                    rng.multivariate_normal(
                        self._coefficients[equation],
                        covariance * self.config.forecast_uncertainty_scale,
                    )
                )
            history = self._last_values.copy()
            previous_policy = self._policy_history[-1]
            persistent_policy_shock = 0.0
            for step in range(horizon):
                regressors = [1.0]
                for lag in range(1, self.config.lags + 1):
                    regressors.extend(history[-lag])
                regressors.append(policy_path[step] - self._policy_history.mean())
                policy_change = policy_path[step] - previous_policy
                persistent_policy_shock = (
                    policy_change
                    + self.config.policy_shock_persistence
                    * persistent_policy_shock
                )
                regressors.append(persistent_policy_shock)
                prediction = np.array(
                    [
                        np.dot(simulated_coefficients[equation], regressors)
                        for equation in range(len(self._fit_variables))
                    ]
                )
                prediction += rng.multivariate_normal(
                    np.zeros(len(self._fit_variables)),
                    self._residual_covariance * self.config.forecast_uncertainty_scale,
                )
                # The historical policy coefficients include the central bank's
                # reaction to economic conditions. Remove that reverse-causality
                # channel before applying structural transmission below.
                for position in range(len(self._fit_variables)):
                    prediction[position] -= (
                        simulated_coefficients[position][-2]
                        * (policy_path[step] - self._policy_history.mean())
                        + simulated_coefficients[position][-1]
                        * persistent_policy_shock
                    )
                policy_gap = policy_path[step] - self._policy_history[-1]
                previous_policy_gap = previous_policy - self._policy_history[-1]
                inflation_adjustment = -self.config.inflation_policy_sensitivity * (
                    policy_gap
                    + self.config.inflation_policy_lag_weight * previous_policy_gap
                )
                for name in ("core_inflation", "headline_inflation"):
                    if name in fit_positions:
                        position = fit_positions[name]
                        prediction[position] += inflation_adjustment
                for name, position in fit_positions.items():
                    simulations[draw, step, self.variables.index(name)] = prediction[position]
                history = np.vstack([history, prediction])[-self.config.lags :]
                previous_policy = policy_path[step]
            if self._gdp_model is not None:
                driver_paths = pd.DataFrame(
                    simulations[draw, :, :],
                    columns=self.variables,
                ).loc[:, self._fit_variables]
                driver_paths[policy_name] = policy_path
                gdp_path = self._gdp_model.forecast(
                    driver_paths=driver_paths,
                    policy_sensitivity=self.config.gdp_policy_sensitivity,
                )["aggregate_growth"].to_numpy()
                simulations[
                    draw, :, self.variables.index("ca_gdp_growth")
                ] = gdp_path

        lower, mean, upper = np.quantile(
            simulations, [0.10, 0.50, 0.90], axis=0
        )
        index = self._future_index(horizon)
        output = pd.DataFrame(index=index)
        for position, name in enumerate(self.variables):
            output[f"{name}_mean"] = mean[:, position]
            output[f"{name}_lower80"] = lower[:, position]
            output[f"{name}_upper80"] = upper[:, position]
        output[f"{policy_name}_mean"] = policy_path
        output[f"{policy_name}_lower80"] = policy_path
        output[f"{policy_name}_upper80"] = policy_path
        output.index.name = self._index.name or "period"
        return output

    def annual_forecast(self, forecast: pd.DataFrame) -> pd.DataFrame:
        """Aggregate quarterly forecast output into calendar-year averages."""
        means = forecast.filter(regex="_mean$")
        if isinstance(forecast.index, (pd.PeriodIndex, pd.DatetimeIndex)):
            years = forecast.index.year
        else:
            raise ValueError("forecast must have a quarterly PeriodIndex or date index")
        annual = means.groupby(years).mean()
        annual.index.name = "year"
        return annual

    def policy_transmission_effects(self) -> pd.DataFrame:
        """Return estimated one-unit policy-level and shock effects.

        A policy-level effect is the coefficient on the policy-rate gap.
        A shock effect is the coefficient on the monetary policy shock.
        Forecasts use the shock effect with the configured persistence.
        """
        self._require_fit()
        return pd.DataFrame(
            {
                "policy_level_effect": [
                    coefficients[-2]
                    for coefficients in self._coefficients
                ],
                "policy_shock_effect": [
                    coefficients[-1]
                    for coefficients in self._coefficients
                ],
            },
            index=self._fit_variables,
        )

    def forecast_gdp_components(
        self,
        forecast: pd.DataFrame,
        risk: str = "central",
    ) -> pd.DataFrame:
        """Return the attached GDP component forecast for BVAR driver paths."""
        self._require_fit()
        if self._gdp_model is None:
            raise RuntimeError("fit the model with component_levels first")
        if risk not in {"central", "low", "high"}:
            raise ValueError("risk must be central, low, or high")
        suffix = {"central": "_mean", "low": "_lower80", "high": "_upper80"}[risk]
        drivers = pd.DataFrame(index=forecast.index)
        for name in self._fit_variables:
            if name == self.config.policy_variable:
                continue
            drivers[name] = forecast[f"{name}{suffix}"]
        drivers[self.config.policy_variable] = forecast[
            f"{self.config.policy_variable}_mean"
        ]
        return self._gdp_model.forecast(
            driver_paths=drivers,
            risk=risk,
            policy_sensitivity=self.config.gdp_policy_sensitivity,
        )

    @property
    def gdp_components(self) -> tuple[str, ...]:
        """Return the attached expenditure-component names."""
        if self._gdp_model is None:
            raise RuntimeError("fit the model with component_levels first")
        return tuple(self._gdp_model.components)

    def _future_index(self, horizon: int) -> pd.Index:
        last = self._index[-1]
        if isinstance(last, pd.Period):
            return pd.period_range(last + 1, periods=horizon, freq=last.freq)
        if isinstance(last, pd.Timestamp):
            return pd.period_range(last.to_period("Q") + 1, periods=horizon, freq="Q")
        return pd.RangeIndex(start=len(self._history), stop=len(self._history) + horizon)

    def _require_fit(self) -> None:
        if not self._fitted:
            raise RuntimeError("fit the model before requesting a forecast")


def load_quarterly_csv(
    path: str,
    date_column: str = "date",
    variables: Sequence[str] | None = None,
) -> pd.DataFrame:
    """Load and validate a quarterly model dataset from CSV."""
    data = pd.read_csv(path, parse_dates=[date_column]).set_index(date_column)
    if variables is not None:
        data = data.loc[:, list(variables)]
    return data.sort_index()


